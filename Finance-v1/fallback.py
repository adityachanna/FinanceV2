def _num(value):
    try:
        if value in (None, "N/A") or value != value:
            return None
        return float(value)
    except (TypeError, ValueError):
        return None


def money(value, currency="USD"):
    value = _num(value)
    if value is None:
        return "n/a"
    sign = "-" if value < 0 else ""
    value = abs(value)
    for size, suffix in [(1e12, "T"), (1e9, "B"), (1e6, "M")]:
        if value >= size:
            return f"{sign}{value / size:,.2f}{suffix} {currency}"
    return f"{sign}{value:,.2f} {currency}"


def pct(value, digits=1, already_percent=False):
    value = _num(value)
    if value is None:
        return "n/a"
    return f"{value if already_percent else value * 100:+.{digits}f}%"


def share(value):
    """Unsigned percentage for levels such as margins (input as a fraction)."""
    value = _num(value)
    return "n/a" if value is None else f"{value * 100:.1f}%"


def ratio(value):
    value = _num(value)
    return "n/a" if value is None else f"{value:,.1f}x"


def find_ticker(text):
    """Return the most likely ticker in a question, or None."""
    lower = f" {text.lower()} "
    for name in sorted(COMPANY_NAMES, key=len, reverse=True):
        if re.search(rf"(?<![a-z]){re.escape(name)}(?![a-z])", lower):
            return COMPANY_NAMES[name]
    explicit = re.findall(r"\$([A-Za-z][A-Za-z.\-]{0,9})", text)
    if explicit:
        return explicit[0].upper()
    for word in re.findall(r"\b[A-Z]{1,5}(?:[.\-][A-Z]{1,3})?\b", text):
        if word not in STOPWORDS:
            return word
    # Last resort: ask Yahoo to resolve a company name.
    words = [w for w in re.findall(r"[A-Za-z][A-Za-z&'.-]{2,}", text) if w.upper() not in STOPWORDS]
    for word in words:
        if word.lower() in {"what", "how", "tell", "about", "stock", "share", "shares", "company", "price",
                            "valuation", "value", "doing", "is", "the", "explain", "give", "show", "should",
                            "overvalued", "undervalued", "financials", "performance", "market", "risk", "today",
                            "this", "that", "with", "does", "worth", "compare", "versus", "buy", "sell", "now"}:
            continue
        try:
            quotes = yf.Search(word, max_results=3, news_count=0).quotes
            equity = [q for q in quotes if q.get("quoteType") == "EQUITY"]
            if equity:
                return equity[0]["symbol"]
        except Exception:
            return None
    return None


def detect_intent(text):
    lower = f" {text.lower()} "
    scores = {intent: sum(word in lower for word in words) for intent, words in INTENTS.items()}
    best = max(scores, key=scores.get)
    return best if scores[best] else None


def _info(ticker):
    stock = yf.Ticker(ticker)
    info = stock.info or {}
    if not (info.get("currentPrice") or info.get("regularMarketPrice") or info.get("longName")):
        raise LookupError(f"Yahoo Finance returned no data for {ticker}.")
    return stock, info


def _range_position(price, low, high):
    price, low, high = _num(price), _num(low), _num(high)
    if None in (price, low, high) or high <= low:
        return None
    return (price - low) / (high - low)


def valuation_answer(ticker, footer=True):
    stock, info = _info(ticker)
    name = info.get("longName") or ticker
    cur = info.get("currency", "USD")
    price = info.get("currentPrice") or info.get("regularMarketPrice")
    trailing, forward = _num(info.get("trailingPE")), _num(info.get("forwardPE"))
    peg = _num(info.get("trailingPegRatio") or info.get("pegRatio"))
    target = _num(info.get("targetMeanPrice"))
    lines = [f"**{name} ({ticker}) valuation snapshot**", "",
             f"- Price: {money(price, cur)} · Market cap: {money(info.get('marketCap'), cur)}",
             f"- P/E trailing {ratio(trailing)} · forward {ratio(forward)} · PEG {ratio(peg)}",
             f"- Price/sales {ratio(info.get('priceToSalesTrailing12Months'))} · Price/book {ratio(info.get('priceToBook'))}"
             f" · EV/EBITDA {ratio(info.get('enterpriseToEbitda'))}"]
    if trailing and trailing > 0:
        lines.append(f"- Earnings yield (1 ÷ trailing P/E): {100 / trailing:.2f}%")
    position = _range_position(price, info.get("fiftyTwoWeekLow"), info.get("fiftyTwoWeekHigh"))
    if position is not None:
        lines.append(f"- 52-week range {money(info.get('fiftyTwoWeekLow'), cur)} to {money(info.get('fiftyTwoWeekHigh'), cur)};"
                     f" the price sits {position * 100:.0f}% of the way up")
    if target and _num(price):
        lines.append(f"- Mean analyst target {money(target, cur)} ({pct(target / _num(price) - 1)} from the current price,"
                     f" {info.get('numberOfAnalystOpinions') or 'n/a'} analysts, consensus "
                     f"\"{(info.get('recommendationKey') or 'n/a').replace('_', ' ')}\")")

    peers = PEERS.get(ticker, [])
    peer_rows = []
    for peer in peers:
        try:
            _, p = _info(peer)
            peer_rows.append((peer, _num(p.get("trailingPE")), _num(p.get("forwardPE"))))
        except Exception:
            continue
    if peer_rows:
        lines += ["", "**Against peers (trailing / forward P/E)**",
                  f"- {ticker}: {ratio(trailing)} / {ratio(forward)}"]
        lines += [f"- {peer}: {ratio(t)} / {ratio(f)}" for peer, t, f in peer_rows]

    read = []
    if trailing and forward:
        read.append("Analysts expect earnings to grow, so the forward multiple is lower than the trailing one."
                    if forward < trailing else
                    "The forward multiple is higher than the trailing one, so analysts expect earnings to fall.")
    peer_pes = [t for _, t, _ in peer_rows if t]
    if trailing and peer_pes:
        avg = sum(peer_pes) / len(peer_pes)
        rel = trailing / avg - 1
        if abs(rel) < 0.1:
            read.append(f"Its trailing P/E is close to the peer average ({avg:.1f}x).")
        else:
            read.append(f"Its trailing P/E is {abs(rel) * 100:.0f}% {'above' if rel > 0 else 'below'} the peer average"
                        f" ({avg:.1f}x), so the market prices it at a {'premium' if rel > 0 else 'discount'}.")
    if peg:
        read.append("A PEG below 1 means the multiple is low relative to expected growth." if peg < 1 else
                    "A PEG above 2 means investors pay a lot for each unit of expected growth." if peg > 2 else
                    "A PEG between 1 and 2 is a middle-of-the-road price for its expected growth.")
    if read:
        lines += ["", "**Reading the numbers**", *[f"- {r}" for r in read]]
    lines += ["", "No single multiple decides whether a stock is cheap. These ratios describe how the market prices"
              " the company today. They do not predict its return."]
    if footer:
        lines += ["", _footer()]
    return "\n".join(lines)


def financials_answer(ticker, footer=True):
    stock, info = _info(ticker)
    name = info.get("longName") or ticker
    cur = info.get("financialCurrency") or info.get("currency", "USD")
    lines = [f"**{name} ({ticker}) financial position**", "",
             f"- {info.get('sector', 'n/a')} · {info.get('industry', 'n/a')}",
             f"- Revenue (TTM) {money(info.get('totalRevenue'), cur)} · growth {pct(info.get('revenueGrowth'))} year on year",
             f"- Gross margin {share(info.get('grossMargins'))} · operating margin {share(info.get('operatingMargins'))}"
             f" · net margin {share(info.get('profitMargins'))}",
             f"- Return on equity {share(info.get('returnOnEquity'))} · return on assets {share(info.get('returnOnAssets'))}",
             f"- Cash {money(info.get('totalCash'), cur)} · debt {money(info.get('totalDebt'), cur)}"
             f" · free cash flow {money(info.get('freeCashflow'), cur)}",
             f"- Debt/equity {ratio((_num(info.get('debtToEquity')) or 0) / 100 if info.get('debtToEquity') else None)}"
             f" · current ratio {ratio(info.get('currentRatio'))}"]
    dividend = _num(info.get("dividendYield"))
    if dividend:
        # yfinance (pinned 1.7.0) reports dividendYield in percent units, e.g. 0.31 means 0.31%.
        lines.append(f"- Dividend yield {dividend:.2f}%"
                     f" · payout ratio {share(info.get('payoutRatio'))}")
    cash, debt = _num(info.get("totalCash")), _num(info.get("totalDebt"))
    if cash is not None and debt is not None:
        lines += ["", f"The company holds {'more cash than debt' if cash > debt else 'more debt than cash'}"
                  f" (net {money(cash - debt, cur)})."]
    if footer:
        lines += ["", _footer()]
    return "\n".join(lines)


def performance_answer(ticker):
    stock = yf.Ticker(ticker)
    history = stock.history(period="1y", auto_adjust=False)
    if history.empty:
        raise LookupError(f"No price history is available for {ticker}.")
    close = history.Close.dropna()
    currency = (stock.history_metadata or {}).get("currency", "USD")
    lines = [f"**{ticker} observed price performance**", "",
             f"- Last close {money(close.iloc[-1], currency)} on {close.index[-1].date()}"]
    for days, label in [(5, "1 week"), (21, "1 month"), (63, "3 months"), (126, "6 months"), (len(close) - 1, "1 year")]:
        if len(close) > days > 0:
            lines.append(f"- {label}: {pct(close.iloc[-1] / close.iloc[-days - 1] - 1)}")
    daily = close.pct_change().dropna()
    if len(daily) > 20:
        drawdown = (close / close.cummax() - 1).min()
        lines.append(f"- Annualised volatility (1 year): {daily.std() * (252 ** 0.5) * 100:.1f}%"
                     f" · worst peak-to-trough fall: {drawdown * 100:.1f}%")
    lines += ["", "These are past returns, not a forecast. Closes exclude dividends.", "", _footer()]
    return "\n".join(lines)


def market_answer(horizon=21):
    from research.service import snapshot
    snap = snapshot(horizon=horizon)
    return market_text(snap)


def market_text(snap):
    state, risk, market = snap["state"], snap["risk"], snap.get("market", {})
    fan_end = snap["fan"][-1] if snap.get("fan") else {}
    lines = [f"**S&P 500 regime on {snap['as_of']}: {state['label']}**", "",
             f"- Model probability {state['probability'] * 100:.1f}%; the regime has lasted about"
             f" {state.get('estimated_age', 0):.0f} sessions",
             f"- Chance of switching regime next session: {snap.get('switch_probability_next_session', 0) * 100:.1f}%"]
    if market:
        lines.append(f"- S&P 500 {market.get('spx', 0):,.2f} · VIX {market.get('vix', 0):.2f}"
                     f" · 21-session realised volatility {market.get('realized_volatility_pct', 0):.1f}%")
    lines += ["", f"**Scenarios over the next {snap['horizon']} trading sessions** ({snap.get('simulations', 2000):,} simulated paths)",
              f"- Probability of a loss: {risk['probability_loss'] * 100:.1f}%",
              f"- Probability of a fall of 5% or more: {risk['probability_decline_5pct'] * 100:.1f}%",
              f"- Median return {pct(risk['median_return'])}; 90% range {pct(fan_end.get('p05'))} to {pct(fan_end.get('p95'))}",
              f"- 95% value at risk {risk['var_95'] * 100:.1f}% · expected shortfall {risk['expected_shortfall_95'] * 100:.1f}%",
              "", f"Model {snap['model_id']}, trained on {snap['training_start']} to {snap['training_end']}; snapshot"
              f" {snap['snapshot_id']}. These are model scenarios, not predictions. Gaussian scenarios can understate"
              " extreme losses.", "", NOTE]
    return "\n".join(lines)


def stock_metrics_text(raw):
    """Fallback for the 'Explain company metrics' button. `raw` comes from details.get_stock_details."""
    ticker = raw.get("ticker", "")
    try:
        body = financials_answer(ticker, footer=False).split("\n", 2)[2]
        return f"{valuation_answer(ticker, footer=False)}\n\n**Financial position**\n{body}\n\n{_footer()}"
    except Exception:
        pass
    cur = raw.get("currency", "USD")
    rows = [f"**{raw.get('company_name', ticker)} ({ticker})**", "",
            f"- Price {money(raw.get('current_price'), cur)} · market cap {money(raw.get('market_cap'), cur)}",
            f"- P/E trailing {ratio(raw.get('pe_ratio_trailing'))} · forward {ratio(raw.get('pe_ratio_forward'))}",
            f"- Net margin {pct(raw.get('profit_margin'), already_percent=True)} · ROE {pct(raw.get('roe'), already_percent=True)}",
            f"- Revenue growth {pct(raw.get('revenue_growth'), already_percent=True)} · beta {raw.get('beta', 'n/a')}",
            "", NOTE]
    return "\n".join(rows)


def market_brief_text(regime, pulse, headlines):
    """Fallback for the Macro Pulse brief, using only the supplied JSON."""
    lines = ["**Current regime**"]
    label = None
    if isinstance(regime, dict):
        label = (regime.get("label") or (regime.get("regime") or {}).get("label")
                 or (regime.get("state") or {}).get("label"))
    lines.append(f"- {label or 'The regime label is not available.'}")
    instruments = (pulse or {}).get("instruments", []) if isinstance(pulse, dict) else []
    if instruments:
        lines += ["", "**Cross-asset read**"]
        for item in instruments[:6]:
            price = _num(item.get("price"))
            week, month = _num(item.get("change5dPct")), _num(item.get("change1mPct"))
            moves = [f"{label} {value:+.2f}%" for label, value in (("5 days", week), ("1 month", month)) if value is not None]
            lines.append(f"- {item.get('name') or item.get('ticker') or item.get('symbol')}: "
                         f"{f'{price:,.2f}' if price is not None else 'n/a'}" + (f" ({', '.join(moves)})" if moves else ""))
        falling = [i.get("name") for i in instruments if (_num(i.get("change1mPct")) or 0) < -3]
        rising = [i.get("name") for i in instruments if (_num(i.get("change1mPct")) or 0) > 3]
        if falling or rising:
            lines += ["", "**What to watch**"]
            if rising:
                lines.append(f"- Up more than 3% over a month: {', '.join(filter(None, rising))}")
            if falling:
                lines.append(f"- Down more than 3% over a month: {', '.join(filter(None, falling))}")
    if headlines:
        lines += ["", "**Headlines to watch**"] + [f"- {h.get('title', '')}" for h in headlines[:3] if h.get("title")]
    lines += ["", NOTE]
    return "\n".join(lines)


def _footer():
    return f"Source: Yahoo Finance, retrieved {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC. Not investment advice.\n\n{NOTE}"


HELP = ("I can answer from market data without an AI key. Try:\n"
        "- \"What is Apple's valuation?\" or \"Is NVDA overvalued?\"\n"
        "- \"Show Microsoft financials\"\n"
        "- \"How has Tesla performed?\"\n"
        "- \"What is the market risk right now?\"\n\n" + NOTE)


def answer(query):
    """Answer a free-text question from data. Always returns text and never raises."""
    query = (query or "").strip()
    if not query:
        return HELP
    intent = detect_intent(query)
    ticker = None if intent == "market" else find_ticker(query)
    try:
        if intent == "market" or (ticker is None and intent is None and re.search(r"s&p|spx|vix", query, re.I)):
            return market_answer()
        if ticker is None:
            return "I could not tell which company you mean. Name it or give its ticker, for example AAPL.\n\n" + HELP
        if intent == "performance":
            return performance_answer(ticker)
        if intent == "financials":
            return financials_answer(ticker)
        return valuation_answer(ticker)
    except Exception as error:
        return f"I could not load data for {ticker or 'that request'}: {error}\n\n{NOTE}"
